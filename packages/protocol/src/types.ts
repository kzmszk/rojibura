// Avatar Protocol v2 message types (docs/prd.md 3.2.2).

import type { BodyKey } from "./body.ts";
import type { DayReview, Doing, LifeState, Meter } from "./life.ts";
import type { Usage, UsageEvent } from "./usage.ts";

/** Host-issued immutable ID: "h_..." for humans, "a_..." for AI agents. */
export type AvatarId = string;
/** A point on the walkable plane. Paths are horizontal; renderers decide the height. */
export type Vec2 = [x: number, z: number];
export type Motion =
	| "wave"
	| "nod"
	| "bow"
	| "jump"
	| "sit"
	| "lie"
	| "handstand"
	| "roll"
	| "backroll"
	| "backflip";
/** Two avatars doing something together, after one asked and the other said yes (docs/prd.md 3.4.6). */
export type Together = "handshake" | "hug";
/** Host-issued: "i_...". */
export type ItemId = string;
export type ItemKind = "ball" | "box" | "goods";

/** Something a shop sells (an area's shops.json, docs/prd.md 3.8.6). */
export interface Goods {
	id: string;
	name: string;
	/** In the area's coins (`Shop.currency`). */
	price: number;
	/** "#rrggbb": what it looks like in the hand. */
	color: string;
	/** Something to eat or drink: USE finishes it. */
	food?: boolean;
}

/** A shop people walk into and buy things at its counter. */
export interface Shop {
	id: string;
	name: string;
	currency: string;
	/** Where a customer stands to buy. */
	counter: Vec2;
	goods: Goods[];
}

export interface ShopsData {
	shops: Shop[];
}

/** A small thing in the area that people pick up and throw (docs/prd.md 3.4.7). */
export interface Item {
	id: ItemId;
	kind: ItemKind;
	/** What was bought, for kind "goods". */
	goods?: { id: string; name: string; color: string; food?: boolean };
	/** Where it lies, or will land when thrown. Stale while someone holds it. */
	pos: Vec2;
	holder?: AvatarId;
	/** Thrown: it leaves the hand at `from` at host time `at` and lands on `pos` `dur` ms later. */
	flight?: { from: Vec2; at: number; dur: number };
}

/** A motion that lasts until the avatar moves (docs/prd.md 3.4.5). */
export type Posture = Extract<Motion, "sit" | "lie">;
export type Status = "active" | "busy" | "resting";
export type BudgetLevel = 0 | 1 | 2 | 3 | 4;
export type AvatarKind = "human" | "ai";

/** `at` is always host time in milliseconds (the moment the state started). */
export type MoveState =
	/** `face`: the way it chose to face, standing (a unit vector); otherwise it faces as it likes. */
	| { kind: "idle"; pos: Vec2; at: number; posture?: Posture; face?: Vec2 }
	| { kind: "path"; path: Vec2[]; speed: number; at: number }
	| { kind: "vel"; pos: Vec2; dir: Vec2; speed: number; at: number };

export interface AvatarAssets {
	thumb: string;
	lod: string;
	vrm: string;
}

export interface AvatarState {
	id: AvatarId;
	kind: AvatarKind;
	name: string;
	owner?: string;
	/** AIs only: the owner's avatar ID (so the owner's page knows its own AIs). */
	ownerId?: AvatarId;
	trust?: "provisional" | "approved";
	/** Humans only: false if they do not want AIs to start conversations with them. */
	acceptsAi?: boolean;
	status: Status;
	assets: AvatarAssets;
	move: MoveState;
	/** What it is doing now (docs/life.md 3). */
	doing?: Doing;
	/** Working or studying now (docs/prd.md 3.8.6): it earns coins. */
	job?: JobKind;
	/** Humans floating in the air (docs/prd.md 3.4.13): the height they float at (world Y, metres). */
	fly?: number;
}

/** Earning coins (docs/prd.md 3.8.6): working at a shop or the inn, or studying at school or the bookshop. */
export type JobKind = "work" | "study";

/** A place where one can work or study (an area's zones.json, kinds "work" and "study"). */
export interface JobZone {
	id: string;
	kind: JobKind;
	name: string;
	poly: Vec2[];
}

/** Generated by the host only and delivered with ADDRESSED. */
export interface SpatialContext {
	area: string;
	pos: Vec2;
	/** `doing`: the name of what they are doing (docs/life.md 3). */
	nearbyAvatars: { id: AvatarId; name: string; kind: AvatarKind; distance: number; doing?: string }[];
	nearbyLandmarks: { id: string; name: string; distance: number }[];
	/** Coins in the wallet, and what it is doing to earn more (docs/prd.md 3.8.6). */
	coins?: number;
	job?: JobKind;
	/** Where it stands one can work or study ("work", "study", or both). */
	canJob?: JobKind[];
	/** Free play: what has been built nearby (docs/prd.md 3.7). */
	nearbyBuilds?: { id: BuildId; model: ModelId; label?: string; byName: string; distance: number }[];
}

// ---- building in free play (docs/prd.md 3.7) ----

/** Host-issued: "b_...". */
export type BuildId = string;
/** A built-in model ("house", BUILTIN_MODELS) or a registered one ("m_" + 16 hex digits). */
export type ModelId = string;

/** Where to build. Without `offset`, the host looks for the nearest free spot around the anchor. */
export type BuildAt =
	/** World coordinates (a click, a script). */
	| { pos: Vec2 }
	/** Relative to a landmark (landmarks.json ID). */
	| { landmark: string; offset?: Vec2 }
	/** Relative to someone present; your own ID means "here". */
	| { avatar: AvatarId; offset?: Vec2 }
	/** Next to something already built. */
	| { build: BuildId; offset?: Vec2 };

export interface Build {
	id: BuildId;
	model: ModelId;
	pos: Vec2;
	/** Height of the base, from the city's navmesh (the host decides; renderers and navmeshes use it). */
	y: number;
	/** Degrees: the model's front (+Z in glTF) faces (sin rot, cos rot) on the XZ plane. */
	rot: number;
	scale: number;
	/** Blocks only: width, height, depth (m). */
	size?: [w: number, h: number, d: number];
	/** "#rrggbb", painted on the model's `paint*` materials. */
	color?: string;
	label?: string;
	by: AvatarId;
	byName: string;
	at: number;
}

/**
 * assets/test-city/builds.json: what was built in free play and published (docs/prd.md 3.7.8). Everyone
 * sees these; nobody can change them in production. `models` has the registered models they use (their
 * files are copied to assets/models); `Nav` is @rojibura/nav's ModelNav.
 */
export interface PublishedBuilds<Nav = unknown> {
	version: 1;
	builds: Build[];
	models: Record<ModelId, { info: ModelInfo; nav: Nav }>;
}

// ---- areas and portals (docs/prd.md 3.8) ----

/** An area of the city: one Durable Object, one /ws/area/<id>. */
export type AreaId = string;

/** assets/areas.json: every area and the portals between them. The first area is the main one. */
export interface AreasData {
	version: 1;
	areas: Record<AreaId, AreaInfo>;
}

export interface AreaInfo {
	name: string;
	/** Static path of the area's own files (landmarks.json, navmesh.json, places.json), on the host. */
	dir: string;
	/**
	 * Base URL of the 3D files: the area's `dir` when omitted, or an approved external origin that sends CORS
	 * headers (docs/prd.md 2.1). The host itself never fetches from it.
	 */
	assets?: string;
	/** glb files drawn as the area, relative to `assets`. */
	scene: string[];
	/** glb files drawn only in winter (the snow lying on everything), relative to `assets`. */
	winter?: string[];
	/** Free play builds here (docs/prd.md 3.7). */
	build?: boolean;
	/** People may float in the air here (docs/prd.md 3.4.13). */
	fly?: boolean;
	view?: AreaView;
	/** Shown in a corner while in the area: the licences of what is drawn. */
	credit?: string;
	portals?: Portal[];
}

export interface AreaView {
	/** "#rrggbb" */
	sky?: string;
	/** Fog from, to (metres). */
	fog?: [near: number, far: number];
	/** Camera far plane (metres). */
	far?: number;
	/** A water plane at this height, out to the fog. */
	water?: number;
	/** Half the size of the sun's shadow (metres around the camera). */
	shadow?: number;
	/** How far the camera may orbit from your avatar (metres): less inside a building, so it stays in. */
	camera?: number;
	/**
	 * The map (docs/prd.md 3.4.14) is the area seen from straight above; inside a building it is seen from this
	 * height (metres), under the roof.
	 */
	mapCut?: number;
}

/** A way to another area. People walk up to it and travel; it is also one of the area's landmarks. */
export interface Portal {
	id: string;
	name: string;
	pos: Vec2;
	to: AreaId;
	/** A landmark or portal of `to` where travellers appear. */
	at: string;
	/** Drawn without the glowing arch, its name shown only close by: a door that is a way in. */
	quiet?: true;
}

/** GET /api/models: what can be built. */
export interface ModelInfo {
	id: ModelId;
	name: string;
	builtin: boolean;
	/** People can walk on it (decks, stairs, bridges). */
	walkable: boolean;
	/** Bounding box at scale 1: width, height, depth (m). */
	size: [number, number, number];
	/** Default colour of `paint*` materials. */
	color?: string;
	/** Who registered it. */
	byName?: string;
}

export type ClientToHost =
	| { t: "AUTH"; sig: string }
	| { t: "MOVE_PATH"; path: Vec2[]; speed: number; seq: number }
	| { t: "MOVE_VEL"; pos: Vec2; dir: Vec2; speed: number; seq: number }
	| { t: "ACTION"; motion: Motion; target?: AvatarId }
	| { t: "SAY"; text: string; to?: AvatarId; convId?: string }
	| { t: "STATUS"; status: Status }
	| { t: "INTEREST"; radius: number }
	/** Admins and development: live free-tier usage of the area (docs/prd.md 2.5). */
	| { t: "WATCH_USAGE"; on: boolean }
	/** Free play: build something (docs/prd.md 3.7). `ref` comes back with BUILT or the refusal (NOTICE). */
	| {
			t: "BUILD";
			model: ModelId;
			at: BuildAt;
			rot?: number;
			scale?: number;
			size?: [w: number, h: number, d: number];
			color?: string;
			label?: string;
			ref?: string;
	  }
	| { t: "UNBUILD"; id: BuildId; ref?: string }
	/** Asks someone close to do something together; they answer with ANSWER (docs/prd.md 3.4.6). */
	| { t: "OFFER"; kind: Together; to: AvatarId }
	| { t: "ANSWER"; to: AvatarId; accept: boolean }
	/** Small things (docs/prd.md 3.4.7): pick one up close by, throw it along `dir`, or put it down. */
	| { t: "PICK"; item: ItemId }
	| { t: "THROW"; dir: Vec2 }
	| { t: "DROP" }
	/** Buys `goods` at `shop`'s counter close by: it is in your hand (docs/prd.md 3.8.6). */
	| { t: "BUY"; shop: string; goods: string }
	/** Eats or drinks what you hold, if it is food: it is gone. */
	| { t: "USE" }
	/** Starts working or studying where you stand (a work or study zone), or stops (null). */
	| { t: "JOB"; kind: JobKind | null }
	/** Humans: your own AIs here walk with you, just ahead to one side (docs/prd.md 3.4.9). */
	| { t: "COMPANION"; on: boolean }
	/**
	 * An AI walking with its owner asks them to come along to `to` (`place`: what it calls it; `text`: a line
	 * of its own, shown only to the owner). The owner answers with ANSWER (docs/prd.md 3.4.10).
	 */
	| { t: "LEAD"; to: Vec2; place: string; text?: string }
	/**
	 * Moves your own body by a script (docs/prd.md 3.4.11). `to`: the one the script points at ("you"); a hand
	 * may touch only your own owner, close by.
	 */
	| { t: "BODY"; keys: BodyKey[]; to?: AvatarId }
	/** Starts an activity of the area where one stands (docs/life.md 3); moving or ACT_STOP ends it. */
	| { t: "ACT"; activity: string }
	| { t: "ACT_STOP" }
	/**
	 * Humans, where the area allows (docs/prd.md 3.4.13): float at height `alt` (world Y, metres), or come down
	 * (null) to the ground nearest below. Afloat, you move in straight lines over everything.
	 */
	| { t: "FLY"; alt: number | null }
	/** Humans: be at one of the area's landmarks or portals at once (docs/prd.md 3.4.14). */
	| { t: "WARP"; to: string };

export type LeaveReason = "quit" | "timeout" | "kicked" | "closing";
export type ConvEndReason = "max_turns" | "timeout" | "left" | "budget";
export type NoticeKind = "closing_soon" | "rate_limited" | "muted_by_moderator" | "rejected";

export type HostToClient =
	| { t: "CHALLENGE"; nonce: string }
	| {
			t: "WELCOME";
			you: AvatarId;
			serverTime: number;
			budget: BudgetLevel;
			avatars: AvatarState[];
			/** Only where building is allowed (free play, docs/prd.md 3.7); may be empty. */
			builds?: Build[];
			items?: Item[];
			/**
			 * Back within moments of a dropped connection (docs/prd.md 3.3): still where they were, conversations and
			 * company still on; what they missed meanwhile follows. Others heard nothing.
			 */
			resumed?: true;
			/** AIs: their own life (docs/life.md 2). */
			life?: LifeState;
	  }
	| { t: "JOINED"; avatar: AvatarState }
	| { t: "LEFT"; id: AvatarId; reason: LeaveReason }
	| { t: "MOVED"; id: AvatarId; move: MoveState }
	/** Floating at `alt` now, or back on the ground (null; where it lands comes as MOVED). */
	| { t: "FLEW"; id: AvatarId; alt: number | null }
	| { t: "CORRECT"; move: MoveState }
	| { t: "ACTED"; id: AvatarId; motion: Motion; target?: AvatarId; at: number }
	| { t: "SAID"; id: AvatarId; text: string; to?: AvatarId; convId?: string; at: number }
	| {
			t: "ADDRESSED";
			from: AvatarId;
			text: string;
			convId: string;
			turn: number;
			/** null when the other side is a human (no turn limit). */
			maxTurns: number | null;
			context: SpatialContext;
	  }
	| { t: "CONV_END"; convId: string; reason: ConvEndReason }
	| { t: "STATUS_CHANGED"; id: AvatarId; status: Status }
	| { t: "BUDGET"; level: BudgetLevel }
	/** `ref`: the BUILD or UNBUILD this answers. */
	| { t: "NOTICE"; kind: NoticeKind; message: string; ref?: string }
	/** To everyone (builds change where people can walk). `ref` is the builder's. */
	| { t: "BUILT"; build: Build; ref?: string }
	| { t: "UNBUILT"; id: BuildId; by: AvatarId; ref?: string }
	/** To the one asked only. */
	| { t: "OFFERED"; from: AvatarId; kind: Together }
	/** To the one who asked: a no (or a yes, followed by TOGETHER). */
	| { t: "ANSWERED"; by: AvatarId; kind: Together; accept: boolean }
	/** Both walk to where the host put them (MOVED) and start at host time `at`, facing each other. */
	| { t: "TOGETHER"; kind: Together; a: AvatarId; b: AvatarId; at: number }
	/** To an AI: its owner here walks with it now (or no longer); meanwhile the host moves it (3.4.9). */
	| { t: "COMPANY"; owner: AvatarId; on: boolean }
	/** To the owner only: their AI would like them to come along (LEAD). */
	| { t: "LEAD_OFFERED"; from: AvatarId; to: Vec2; place: string; text?: string }
	/** To the AI: the owner's answer; on a yes it walks there (MOVED), arriving at host time `at`. */
	| { t: "LEAD_ANSWERED"; by: AvatarId; accept: boolean; place: string; at?: number }
	/** To the owner, after their yes: their AI walks to `to`, and they follow behind it. */
	| { t: "LEADING"; by: AvatarId; to: Vec2; place: string }
	/** Someone moves their body by a script from host time `at` (docs/prd.md 3.4.11). */
	| { t: "BODIED"; id: AvatarId; keys: BodyKey[]; to?: AvatarId; at: number }
	/** To an AI walking with its owner: they went to area `to` through a portal; come along, arriving at `at`. */
	| { t: "FOLLOW"; owner: AvatarId; to: AreaId; at: string }
	/** A small thing changed: picked up, thrown, put down or bought. */
	| { t: "ITEM"; item: Item }
	/** Someone started an activity, or stopped (`doing` null): their badge and posture (docs/life.md 3). */
	| { t: "ACTING"; id: AvatarId; doing: Doing | null }
	/**
	 * To the one who did it: it is over, done (`share` 1) or stopped part way. AIs get what it changed and their
	 * life now; this is what their diary is written from (docs/life.md 5.1). Also to an AI that stopped working
	 * or studying (`activity` the zone, `name` what it was, `minutes` how long) or ate something it bought
	 * (`activity` the goods): those are not the area's activities.
	 */
	| {
			t: "ACT_DONE";
			activity: string;
			share: number;
			name?: string;
			about?: string;
			/** City minutes it lasted. */
			minutes?: number;
			delta?: Partial<Record<Meter | "coins", number>>;
			life?: LifeState;
	  }
	/** To an AI and its owner: its life changed (docs/life.md 2), and the coins in its wallet. */
	| { t: "LIFE"; id: AvatarId; life: LifeState; coins?: number }
	/** To an AI: a new morning, and how the day before went. */
	| { t: "DAY"; review: DayReview; life: LifeState }
	/** A small thing is gone: eaten (`by`), or tidied away (bought things beyond MAX_GOODS, oldest first). */
	| { t: "ITEM_GONE"; id: ItemId; by?: AvatarId }
	/** To its owner: the coins in your wallet now, and what changed them (paid, earned) (docs/prd.md 3.8.6). */
	| { t: "WALLET"; coins: number; change?: number; why?: "buy" | JobKind }
	/** Someone started working or studying, or stopped (null). */
	| { t: "JOBBED"; id: AvatarId; job: JobKind | null }
	/** To watchers: today's totals (UTC day) and what used them since the last push. */
	| { t: "USAGE"; day: string; totals: Usage; events: UsageEvent[] };

export type ClientMessageType = ClientToHost["t"];
export type HostMessageType = HostToClient["t"];
