// Avatar Protocol v2 message types (docs/prd.md 3.2.2).

/** Host-issued immutable ID: "h_..." for humans, "a_..." for AI agents. */
export type AvatarId = string;
/** A point on the walkable plane. Paths are horizontal; renderers decide the height. */
export type Vec2 = [x: number, z: number];
export type Motion = "wave" | "nod" | "bow" | "jump" | "sit";
export type Status = "active" | "busy" | "resting";
export type BudgetLevel = 0 | 1 | 2 | 3 | 4;
export type AvatarKind = "human" | "ai";

/** `at` is always host time in milliseconds (the moment the state started). */
export type MoveState =
	| { kind: "idle"; pos: Vec2; at: number }
	| { kind: "path"; path: Vec2[]; speed: number; at: number }
	| { kind: "vel"; pos: Vec2; dir: Vec2; speed: number; at: number };

export interface AvatarAssets {
	thumb: string;
	lod: string;
	vrm: string;
}

export interface AvatarState {
	id: AvatarId;
	kind: AvatarKind;
	name: string;
	owner?: string;
	trust?: "provisional" | "approved";
	status: Status;
	assets: AvatarAssets;
	move: MoveState;
}

/** Generated by the host only and delivered with ADDRESSED. */
export interface SpatialContext {
	area: string;
	pos: Vec2;
	nearbyAvatars: { id: AvatarId; name: string; kind: AvatarKind; distance: number }[];
	nearbyLandmarks: { id: string; name: string; distance: number }[];
}

export type ClientToHost =
	| { t: "AUTH"; sig: string }
	| { t: "MOVE_PATH"; path: Vec2[]; speed: number; seq: number }
	| { t: "MOVE_VEL"; pos: Vec2; dir: Vec2; speed: number; seq: number }
	| { t: "ACTION"; motion: Motion; target?: AvatarId }
	| { t: "SAY"; text: string; to?: AvatarId; convId?: string }
	| { t: "STATUS"; status: Status }
	| { t: "INTEREST"; radius: number };

export type LeaveReason = "quit" | "timeout" | "kicked" | "closing";
export type ConvEndReason = "max_turns" | "timeout" | "left" | "budget";
export type NoticeKind = "closing_soon" | "rate_limited" | "muted_by_moderator" | "rejected";

export type HostToClient =
	| { t: "CHALLENGE"; nonce: string }
	| { t: "WELCOME"; you: AvatarId; serverTime: number; budget: BudgetLevel; avatars: AvatarState[] }
	| { t: "JOINED"; avatar: AvatarState }
	| { t: "LEFT"; id: AvatarId; reason: LeaveReason }
	| { t: "MOVED"; id: AvatarId; move: MoveState }
	| { t: "CORRECT"; move: MoveState }
	| { t: "ACTED"; id: AvatarId; motion: Motion; target?: AvatarId; at: number }
	| { t: "SAID"; id: AvatarId; text: string; to?: AvatarId; convId?: string; at: number }
	| {
			t: "ADDRESSED";
			from: AvatarId;
			text: string;
			convId: string;
			turn: number;
			/** null when the other side is a human (no turn limit). */
			maxTurns: number | null;
			context: SpatialContext;
	  }
	| { t: "CONV_END"; convId: string; reason: ConvEndReason }
	| { t: "STATUS_CHANGED"; id: AvatarId; status: Status }
	| { t: "BUDGET"; level: BudgetLevel }
	| { t: "NOTICE"; kind: NoticeKind; message: string };

export type ClientMessageType = ClientToHost["t"];
export type HostMessageType = HostToClient["t"];
